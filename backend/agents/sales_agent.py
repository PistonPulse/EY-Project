"""
sales_agent.py
==============

Production worker agent for the **sales & advisory** stages of the
lending chatbot.

Covered States
--------------
- ``GREETING``          — welcome and capture applicant name.
- ``PURPOSE``           — discover the loan purpose / product category.
- ``LOAN_AMOUNT``       — capture the requested amount and compute indicative EMI.
- ``OFFER_PRESENTATION``— present personalised loan offers with EMI breakdowns.
- ``TENURE_SELECTION``  — help the user pick a tenure; handle affordability concerns.

Responsibilities
----------------
1. **Discover loan purpose** — map free-text input to a canonical category.
2. **Explain EMI and tenure** — use the deterministic ``emi_calculator`` to
   show monthly payments, total interest, and cost comparisons.
3. **Handle affordability concerns** — if EMI > 50 % FOIR, proactively
   suggest a longer tenure or lower amount.
4. **Suggest alternatives** — generate a comparison table of 3 tenure
   options so the user can make an informed choice.
5. **Dynamic responses** — all user-facing messages are composed from
   parameterised templates; no hard-coded strings in business logic.

Design Notes
------------
- **No AI for calculations** — all EMI, interest, and affordability numbers
  come from pure arithmetic in ``backend.core.emi_calculator``.
- Templates are defined in ``TEMPLATES`` at the bottom of this file for
  locality; they can be moved to a shared registry later.
"""

