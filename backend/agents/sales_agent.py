# Helper Functions (pure, no side-effects)
# ═══════════════════════════════════════════════════════════════════════════

def _fmt(n: float) -> str:
    """Format a number Indian-style with commas (approx)."""
    if n >= 1_00_00_000:
        return f"{n / 1_00_00_000:,.2f} Cr"
    if n >= 1_00_000:
        return f"{n / 1_00_000:,.2f} L"
    return f"{n:,.0f}"


def _parse_amount(text: str) -> Optional[float]:
    """
    Extract a loan amount from free-text input.

    Handles patterns like:
    - "500000", "5,00,000", "₹5,00,000"
    - "5 lakh", "5L", "50 lac"
    - "1 crore", "1.5 cr", "1.5Cr"
    """
    text = text.strip().lower().replace("₹", "").replace(",", "").replace(" ", "")

    # Crore pattern
    m = re.match(r"^(\d+\.?\d*)\s*(crore|cr)s?$", text)
    if m:
        return float(m.group(1)) * 1_00_00_000

    # Lakh pattern
    m = re.match(r"^(\d+\.?\d*)\s*(lakh|lac|l)s?$", text)
    if m:
        return float(m.group(1)) * 1_00_000

    # Thousand pattern
    m = re.match(r"^(\d+\.?\d*)\s*(thousand|k)s?$", text)
    if m:
        return float(m.group(1)) * 1_000

    # Plain number
    m = re.match(r"^(\d+\.?\d*)$", text)
    if m:
        return float(m.group(1))

    return None


def _detect_purpose(text: str) -> Optional[str]:
    """Map free-text input to a canonical loan-purpose key."""
    normalised = text.strip().lower()
    # Direct lookup
    if normalised in PURPOSE_SYNONYMS:
        return PURPOSE_SYNONYMS[normalised]
    # Substring search
    for keyword, purpose in PURPOSE_SYNONYMS.items():
        if keyword in normalised:
            return purpose
    return None


def _build_emi_table(
    principal: float,
    rate: float,
    tenures: List[int],
    income: Optional[float] = None,
) -> Tuple[str, List[EMIOption]]:
    """
    Build a Markdown comparison table for multiple tenure options.

    Returns the formatted table string AND the list of ``EMIOption`` rows.
    """
    options: List[EMIOption] = []
    for t in tenures:
        emi = calculate_emi(principal, rate, t)
        total_interest = compute_total_interest(principal, rate, t)
        total = round(principal + total_interest, 2)
        affordable = check_affordability(income, emi) if income and income > 0 else True
        options.append(EMIOption(t, emi, total_interest, total, affordable))

    lines = ["| Tenure | EMI/month | Total Interest | Total Payment | Status |"]
    lines.append("|--------|-----------|----------------|---------------|--------|")
    for o in options:
        status = "✅" if o.affordable else "⚠️"
        lines.append(
            f"| {o.tenure_months} mo | ₹{_fmt(o.emi)} | ₹{_fmt(o.total_interest)} "
            f"| ₹{_fmt(o.total_payment)} | {status} |"
        )
    return "\n".join(lines), options


def _build_alternatives(
    principal: float, rate: float, income: float, current_tenure: int
) -> str:
    """Suggest reduced amounts or longer tenures to fix affordability."""
    suggestions: List[str] = []

    # Option A — extend tenure
    for t in (current_tenure + 12, current_tenure + 24, current_tenure + 36):
        alt_emi = calculate_emi(principal, rate, t)
        if check_affordability(income, alt_emi):
            suggestions.append(
                f"📌 **Extend to {t} months** → EMI drops to ₹{_fmt(alt_emi)}/month"
            )
            break

    # Option B — reduce amount (try 80%, 60%)
    for pct in (0.80, 0.60):
        reduced = round(principal * pct)
        alt_emi = calculate_emi(reduced, rate, current_tenure)
        if check_affordability(income, alt_emi):
            suggestions.append(
                f"📌 **Reduce amount to ₹{_fmt(reduced)}** → EMI falls to ₹{_fmt(alt_emi)}/month"
            )
            break

    return "\n".join(suggestions) if suggestions else "Consider co-applying with a guarantor to improve eligibility."


def _extract_name(text: str) -> Optional[str]:
    """Best-effort name extraction from a short user message."""
    # Strip common prefixes
    cleaned = re.sub(
        r"^(my name is|i am|i'm|this is|call me|it's|its)\s+",
        "",
        text.strip(),
        flags=re.IGNORECASE,
    )
    # Take up to 4 words, alphabetic only
    words = [w for w in cleaned.split() if re.match(r"^[a-zA-Z]+$", w)]
    if words:
        return " ".join(words[:4]).title()
    return None


def _render(template_key: str, **kwargs) -> str:
    """Render a response template, silently ignoring missing keys."""
    tpl = TEMPLATES.get(template_key, "")
    try:
        return tpl.format(**kwargs)
    except KeyError:
        return tpl


