# Sales Agent
# ═══════════════════════════════════════════════════════════════════════════

class SalesAgent(BaseAgent):
    """
    Handles greeting, purpose discovery, loan amount capture, offer
    presentation, and tenure selection — all powered by deterministic
    EMI calculations and parameterised response templates.
    """

    def __init__(self) -> None:
        super().__init__(name="sales")

    async def process(
        self,
        session_id: str,
        user_message: str,
        context: Dict[str, Any],
    ) -> AgentResult:
        """
        Route to the correct handler based on the current conversation state.
        """
        state = context.get("state", "")
        collected = context.get("collected_data", {})
        self.logger.info("SalesAgent | session=%s state=%s", session_id, state)

        handler = {
            "greeting":           self._handle_greeting,
            "purpose":            self._handle_purpose,
            "loan_amount":        self._handle_loan_amount,
            "offer_presentation": self._handle_offers,
            "tenure_selection":   self._handle_tenure,
        }.get(state, self._handle_fallback)

        return await handler(session_id, user_message, collected, context)

    # ── GREETING ────────────────────────────────────────────────────────

    async def _handle_greeting(
        self, session_id: str, msg: str, collected: Dict, ctx: Dict
    ) -> AgentResult:
        """Capture applicant name and welcome them."""
        name = _extract_name(msg)
        if not name:
            return AgentResult(
                success=True,
                message=_render("welcome", name_part=""),
                data={},
            )

        return AgentResult(
            success=True,
            message=_render("name_captured", name=name),
            data={"applicant_name": name},
        )

    # ── PURPOSE ─────────────────────────────────────────────────────────

    async def _handle_purpose(
        self, session_id: str, msg: str, collected: Dict, ctx: Dict
    ) -> AgentResult:
        """Discover the loan purpose from the user's message."""

        # Check for EMI explanation requests
        if any(kw in msg.lower() for kw in ("what is emi", "explain emi", "emi meaning", "emi kya")):
            return await self._explain_emi(collected)

        purpose = _detect_purpose(msg)
        if not purpose:
            return AgentResult(
                success=True,
                message=_render("purpose_unknown"),
                data={},
            )

        rate = DEFAULT_RATES.get(purpose, 12.0)
        tenures = TENURE_OPTIONS.get(purpose, [12, 24, 36, 48, 60])
        tenure_str = " · ".join(f"{t} mo" for t in tenures)

        return AgentResult(
            success=True,
            message=_render(
                "purpose_confirmed",
                purpose_title=purpose.title(),
                rate=rate,
                tenures=tenure_str,
            ),
            data={"loan_purpose": purpose},
        )

    # ── LOAN AMOUNT ─────────────────────────────────────────────────────

    async def _handle_loan_amount(
        self, session_id: str, msg: str, collected: Dict, ctx: Dict
    ) -> AgentResult:
        """Capture the requested loan amount and show indicative EMI table."""

        # EMI explanation mid-stage
        if any(kw in msg.lower() for kw in ("what is emi", "explain emi", "emi meaning")):
            return await self._explain_emi(collected)

        amount = _parse_amount(msg)
        if amount is None:
            return AgentResult(
                success=True,
                message=_render("amount_invalid"),
                data={},
            )

        if amount < 10_000 or amount > 5_00_00_000:
            return AgentResult(
                success=True,
                message=_render("amount_invalid"),
                data={},
            )

        purpose = collected.get("loan_purpose", "personal")
        rate = DEFAULT_RATES.get(purpose, 12.0)
        tenures = TENURE_OPTIONS.get(purpose, [12, 24, 36, 48, 60])
        income = collected.get("monthly_income")

        emi_table, options = _build_emi_table(amount, rate, tenures, income)

        return AgentResult(
            success=True,
            message=_render(
                "amount_captured",
                amount_fmt=_fmt(amount),
                purpose_title=purpose.title(),
                emi_table=emi_table,
            ),
            data={
                "loan_amount": amount,
                "requested_amount": amount,
                "indicative_rate": rate,
                "emi_options": [
                    {
                        "tenure": o.tenure_months,
                        "emi": o.emi,
                        "total_interest": o.total_interest,
                        "total_payment": o.total_payment,
                        "affordable": o.affordable,
                    }
                    for o in options
                ],
            },
        )

    # ── OFFER PRESENTATION ──────────────────────────────────────────────

    async def _handle_offers(
        self, session_id: str, msg: str, collected: Dict, ctx: Dict
    ) -> AgentResult:
        """Present loan offers and handle offer selection."""
        offers = collected.get("loan_offers", [])

        # If the user selects an offer by number
        selection = re.match(r"^(\d+)$", msg.strip())
        if selection and offers:
            idx = int(selection.group(1)) - 1
            if 0 <= idx < len(offers):
                offer = offers[idx]
                return AgentResult(
                    success=True,
                    message=_render(
                        "offer_selected",
                        offer_num=idx + 1,
                        amount_fmt=_fmt(offer.get("amount", 0)),
                        tenure=offer.get("tenure", 0),
                        emi_fmt=_fmt(offer.get("emi", 0)),
                        rate=offer.get("rate", 0),
                        interest_fmt=_fmt(offer.get("total_interest", 0)),
                    ),
                    data={"selected_offer_id": offer.get("id", str(idx + 1))},
                )

        # Build the offers table
        if offers:
            lines = ["| # | Amount | Tenure | EMI/mo | Rate |"]
            lines.append("|---|--------|--------|--------|------|")
            for i, o in enumerate(offers, 1):
                lines.append(
                    f"| {i} | ₹{_fmt(o.get('amount', 0))} "
                    f"| {o.get('tenure', 0)} mo "
                    f"| ₹{_fmt(o.get('emi', 0))} "
                    f"| {o.get('rate', 0)}% |"
                )
            table = "\n".join(lines)
            return AgentResult(
                success=True,
                message=_render(
                    "offers_presented",
                    offers_table=table,
                    offer_count=len(offers),
                ),
                data={},
            )

        # No offers generated yet — auto-generate from collected data
        amount = collected.get("loan_amount", 0)
        purpose = collected.get("loan_purpose", "personal")
        rate = DEFAULT_RATES.get(purpose, 12.0)
        tenures = TENURE_OPTIONS.get(purpose, [12, 24, 36, 48, 60])

        generated_offers: List[Dict[str, Any]] = []
        for t in tenures[:3]:  # top 3 tenure options
            emi = calculate_emi(amount, rate, t)
            interest = compute_total_interest(amount, rate, t)
            generated_offers.append({
                "id": f"OFFER-{purpose.upper()}-{t}",
                "amount": amount,
                "tenure": t,
                "emi": emi,
                "rate": rate,
                "total_interest": interest,
            })

        lines = ["| # | Amount | Tenure | EMI/mo | Rate |"]
        lines.append("|---|--------|--------|--------|------|")
        for i, o in enumerate(generated_offers, 1):
            lines.append(
                f"| {i} | ₹{_fmt(o['amount'])} | {o['tenure']} mo "
                f"| ₹{_fmt(o['emi'])} | {o['rate']}% |"
            )
        table = "\n".join(lines)

        return AgentResult(
            success=True,
            message=_render(
                "offers_presented",
                offers_table=table,
                offer_count=len(generated_offers),
            ),
            data={"loan_offers": generated_offers},
        )

    # ── TENURE SELECTION ────────────────────────────────────────────────

    async def _handle_tenure(
        self, session_id: str, msg: str, collected: Dict, ctx: Dict
    ) -> AgentResult:
        """Help the user select a tenure; handle affordability concerns."""
        amount = collected.get("loan_amount", 0)
        purpose = collected.get("loan_purpose", "personal")
        rate = DEFAULT_RATES.get(purpose, 12.0)
        income = collected.get("monthly_income")
        tenures = TENURE_OPTIONS.get(purpose, [12, 24, 36, 48, 60])

        # ── Hesitation detection ────────────────────────────────────────
        hesitation_cues = (
            "not sure", "unsure", "confused", "too much", "too high",
            "expensive", "can't afford", "afford", "worried", "scary",
            "nervous", "think about", "need time", "hmm", "idk",
            "don't know", "which one", "what should",
        )
        if any(cue in msg.lower() for cue in hesitation_cues):
            table, _ = _build_emi_table(amount, rate, tenures, income)
            return AgentResult(
                success=True,
                message=_render(
                    "hesitation_nudge",
                    comparison_table=table,
                ),
                data={},
            )

        # If user asks for comparison
        if any(kw in msg.lower() for kw in ("compare", "comparison", "options", "show me")):
            table, _ = _build_emi_table(amount, rate, tenures, income)
            return AgentResult(
                success=True,
                message=_render(
                    "tenure_comparison",
                    amount_fmt=_fmt(amount),
                    rate=rate,
                    comparison_table=table,
                ),
                data={},
            )

        # Try to parse a tenure value
        m = re.search(r"(\d+)", msg)
        if not m:
            table, _ = _build_emi_table(amount, rate, tenures, income)
            return AgentResult(
                success=True,
                message=_render(
                    "tenure_comparison",
                    amount_fmt=_fmt(amount),
                    rate=rate,
                    comparison_table=table,
                ),
                data={},
            )

        tenure = int(m.group(1))
        emi = calculate_emi(amount, rate, tenure)
        total_interest = compute_total_interest(amount, rate, tenure)
        total = round(amount + total_interest, 2)

        # Affordability check (if income is known)
        if income and income > 0:
            foir = round(emi / income * 100, 1)
            if not check_affordability(income, emi):
                alternatives = _build_alternatives(amount, rate, income, tenure)
                return AgentResult(
                    success=True,
                    message=_render(
                        "affordability_warning",
                        income_fmt=_fmt(income),
                        emi_fmt=_fmt(emi),
                        foir_pct=foir,
                        alternatives=alternatives,
                    ),
                    data={},
                )
            # Passes affordability
            data_out = {"selected_tenure": tenure}
            affordability_msg = _render(
                "affordability_ok",
                emi_fmt=_fmt(emi),
                foir_pct=foir,
            )
        else:
            data_out = {"selected_tenure": tenure}
            affordability_msg = ""

        confirmation = _render(
            "tenure_confirmed",
            tenure=tenure,
            emi_fmt=_fmt(emi),
            total_fmt=_fmt(total),
            interest_fmt=_fmt(total_interest),
        )

        full_msg = f"{affordability_msg}\n\n{confirmation}" if affordability_msg else confirmation

        return AgentResult(
            success=True,
            message=full_msg,
            data=data_out,
        )

    # ── EMI Explanation (reusable) ──────────────────────────────────────

    async def _explain_emi(self, collected: Dict) -> AgentResult:
        """Return a plain-language EMI explanation with numbers if available."""
        amount = collected.get("loan_amount")
        purpose = collected.get("loan_purpose", "personal")
        rate = DEFAULT_RATES.get(purpose, 12.0)
        tenures = TENURE_OPTIONS.get(purpose, [12, 24, 36, 48, 60])
        income = collected.get("monthly_income")

        if amount and amount > 0:
            table, _ = _build_emi_table(amount, rate, tenures, income)
            return AgentResult(
                success=True,
                message=_render(
                    "emi_explanation",
                    amount_fmt=_fmt(amount),
                    rate=rate,
                    emi_table=table,
                ),
                data={},
            )

        # Generic explanation without numbers
        return AgentResult(
            success=True,
            message=(
                "📖 **What is EMI?**\n\n"
                "EMI stands for **Equated Monthly Instalment** — the fixed "
                "amount you pay every month until the loan is fully repaid.\n\n"
                "Each EMI includes a **principal** portion (reduces your loan "
                "balance) and an **interest** portion (cost of borrowing).\n\n"
                "Once we know your loan amount, I'll show you exact EMI "
                "figures for different tenures!"
            ),
            data={},
        )

    # ── Fallback ────────────────────────────────────────────────────────

    async def _handle_fallback(
        self, session_id: str, msg: str, collected: Dict, ctx: Dict
    ) -> AgentResult:
        """Generic fallback when the state doesn't match a known handler."""
        state = ctx.get("state", "unknown")
        tips = {
            "greeting":    "Tell me your full name to get started.",
            "purpose":     "Type your loan type: Personal, Home, Auto, Business, Education, or Gold.",
            "loan_amount": "Enter the amount you need, e.g. '5 lakh' or '500000'.",
        }
        tip = tips.get(state, "Type **help** for guidance.")
        return AgentResult(
            success=True,
            message=_render("fallback", tip=tip),
            data={},
        )
